"""
prompt.py —— Qwen-VL Prompt 模板

B模块职责：
    A / EventEngine：
        根据 Detection + Tracking + 规则确定 event_type。

    B / Qwen-VL：
        已知 event_type 后，
        观察该事件对应的连续视频帧，
        分析人物真实发生的动作，
        生成具体、客观的自然语言 description。

重要原则：
    event_type 是上游已经确定的“分析目标”，
    Qwen-VL 不负责重新分类事件。

正式流程：
    Event(event_type)
        ↓
    Qwen-VL观察连续视频帧
        ↓
    分析真实视觉动作
        ↓
    判断画面是否支持该事件
        ↓
    生成 description
        ↓
    返回补全后的 Event
"""


