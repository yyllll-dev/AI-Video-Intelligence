"""检测模块配置

本文件：src/detection/config.py

职责：
1. 配置 YOLO 模型路径及推理参数；
2. 定义第一版需要关注的基础视觉目标类别；
3. 为 detector.py 提供统一配置。

注意：
- YOLO 负责检测“物体”，不直接判断学习行为。
- reading、writing、phone_learning、phone_distraction 等属于
  行为/事件，由 Tracking、Qwen-VL 和 EventEngine 综合判断。
- 当前使用 YOLO11n 的 COCO 预训练模型，因此不存在
  “study_desk（学习桌）”这一专门类别。
- COCO 中的 “dining table” 仅作为桌面候选目标使用，
  不等同于“学习桌”。
"""

from pathlib import Path


# ============================================================
# 1. 模型配置
# ============================================================

# 模型权重路径（相对项目根目录 models/）
#
# 项目结构：
# 项目根目录/
# ├── models/
# │   └── yolo11n.pt
# └── src/
#     └── detection/
#         └── config.py

MODEL_PATH = (
    Path(__file__).resolve().parents[2]
    / "models"
    / "yolo11n.pt"
)


# ============================================================
# 2. YOLO 推理参数
# ============================================================

# 目标最低置信度。
# 第一版先使用 0.5，后续根据真实学习场景测试结果调整。
CONF_THRESHOLD = 0.5

# NMS（非极大值抑制）的 IoU 阈值。
IOU_THRESHOLD = 0.45

# 第一版先使用 CPU，确保项目能够稳定运行。
# 后续如果设备支持 GPU / NPU，再进行性能优化。
DEVICE = "cpu"


# ============================================================
# 3. YOLO 基础目标类别
# ============================================================

# 这里定义的是 YOLO 需要关注的“物体类别”，
# 不是项目的事件类别。
#
# 项目当前定义的 14 个事件：
# 1.  坐到学习位置
# 2.  离开学习位置
# 3.  学习准备
# 4.  开始学习
# 5.  结束学习
# 6.  学习结束整理
# 7.  阅读
# 8.  书写
# 9.  手机学习
# 10. 电脑学习
# 11. 其他学习行为
# 12. 手机分心
# 13. 电脑分心
# 14. 交流分心
#
# 上述事件不会直接交给 YOLO 判断，
# 而是由 YOLO、Tracking、Qwen-VL、EventEngine
# 综合完成。


ALLOWED_CLASSES = {
    # 人：所有学习行为判断的核心目标
    "person",

    # 椅子：辅助判断学生是否坐到学习位置
    "chair",

    # COCO 中没有“study desk（学习桌）”类别。
    # “dining table”这里只作为桌面候选目标使用，
    # 不代表 YOLO 已经能够识别“学习桌”。
    "dining table",

    # 学习材料
    "book",

    # 手机：用于辅助判断手机学习 / 手机分心
    "cell phone",

    # 电脑：用于辅助判断电脑学习 / 电脑分心
    "laptop",

    # 键盘、鼠标：
    # 作为电脑使用场景的辅助视觉证据，
    # 不直接用于判断“是否学习”。
    "keyboard",
    "mouse",
}


# ============================================================
# 4. 模型缺失时的错误提示
# ============================================================

# 按项目约定：检测模块不偷偷下载或替换模型。
# 如果模型不存在，则提示用户手动下载。

MODEL_DOWNLOAD_HINT = (
    f"未找到 YOLO 权重文件: {MODEL_PATH}\n"
    "请手动下载 yolo11n.pt 并放到 models/ 目录：\n"
    "  - GitHub: "
    "https://github.com/ultralytics/assets/releases/download/v8.3.0/yolo11n.pt\n"
    "  - 或执行："
    "python -c \"from ultralytics import YOLO; "
    "YOLO('yolo11n.pt')\"，"
    "下载后将 yolo11n.pt 移入 models/ 目录。"
)